/* eslint-disable no-bitwise -- Mulberry32 mixes 32-bit integers. */
/** Reproduce the same connection layout in Storybook and the culling benchmark. */
export function mulberry32(seed: number): () => number {
  return () => {
    let t = (seed += 0x6d2b79f5);
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
